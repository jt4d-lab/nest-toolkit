/**
 * Пустой объект.
 *
 * Используется как значение по умолчанию для дженериков, когда у сущности нет
 * разрешений, а у матрицы — связей. Тип полностью эквивалентен литералу `{}`,
 * но записан через `Record`, потому что литерал запрещён правилом
 * `@typescript-eslint/no-empty-object-type`.
 */
export type EmptyObject = Record<never, never>;
